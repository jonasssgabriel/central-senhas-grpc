    /**
     * Trabalho 5 (Jonas, Lucas e Luis) — cada código de status do gRPC é
     * causado por um lado diferente da chamada:
     *  - INVALID_ARGUMENT: a Central recusou o pedido (ex.: nome vazio);
     *  - DEADLINE_EXCEEDED: o prazo do totem (PRAZO_SEGUNDOS) esgotou antes
     *    da Central responder — note que, se o totem repetir o pedido, a
     *    Central (que não sabia se a resposta anterior chegou) numera de
     *    novo: a chamada não é idempotente, por isso "vieram duas senhas";
     *  - UNAVAILABLE: a Central está fora do ar ou inacessível na porta.
     */
    private String mensagemDeErro(StatusRuntimeException e) {
        switch (e.getStatus().getCode()) { // Trabalho 5: getCode() devolve o enum Status.Code (INVALID_ARGUMENT, etc.)
            case INVALID_ARGUMENT:
                // Trabalho 5: getDescription() repete o texto que a Central mandou no withDescription(...)
                return "Dados inválidos: " + e.getStatus().getDescription();
            case DEADLINE_EXCEEDED:
                // Trabalho 5: usa a mesma constante PRAZO_SEGUNDOS pra mensagem não "mentir" se o valor mudar
                return "A Central demorou demais para responder (prazo de "
                        + PRAZO_SEGUNDOS + "s esgotado).";
            case UNAVAILABLE:
                return "Central de Senhas indisponível. Tente novamente."; // Trabalho 5: Central fora do ar/porta errada
            default:
                return "Falha inesperada: " + e.getStatus().getCode(); // Trabalho 5: qualquer outro código não previsto
        }
    }

