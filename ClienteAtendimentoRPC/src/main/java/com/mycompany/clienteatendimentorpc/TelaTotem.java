    private void btnPegarSenhaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPegarSenhaActionPerformed
        String nome = tfNome.getText().trim();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite seu nome.");
            return;
        }
        String local = (String) cbxLocal.getSelectedItem();
        TipoAtendimento tipo = rbPrioritario.isSelected()
                ? TipoAtendimento.PRIORITARIO : TipoAtendimento.NORMAL;
        PedidoSenha pedido = PedidoSenha.newBuilder()
                .setNome(nome).setTipo(tipo).setLocal(local).build();

        btnPegarSenha.setEnabled(false);               // Trabalho 5: trava o botão pra não clicar 2x enquanto espera
        lblMensagem.setText("Aguardando a Central...");  // Trabalho 5: feedback imediato pro usuário, antes da resposta

        try {
            Senha senha = stub.withDeadlineAfter(PRAZO_SEGUNDOS, TimeUnit.SECONDS) // Trabalho 5: PRAZO_SEGUNDOS no lugar do "5" fixo
                    .pegarSenha(pedido);
            lbSenha.setText(senha.getCodigo());
            lblMensagem.setText(senha.getMensagem()); // Trabalho 5: mostra a mensagem completa da Central, não só o código
            tfNome.setText("");
        } catch (StatusRuntimeException e) {
            lbSenha.setText("---");
            lblMensagem.setText(mensagemDeErro(e)); // Trabalho 5: mensagem específica por código, em vez de genérica
            JOptionPane.showMessageDialog(this,
                    "Falha na chamada: " + e.getStatus().getCode());
        } finally {
            btnPegarSenha.setEnabled(true); // Trabalho 5: libera o botão de novo, mesmo quando deu erro
        }
    }//GEN-LAST:event_btnPegarSenhaActionPerformed

